  void drawFastVLine(int x, int y, int h, uint16_t color) {
    fillRect(x, y, 1, h, color);
  }

  void drawRect(int x, int y, int w, int h, uint16_t color) {
    drawFastHLine(x, y, w, color);
    drawFastHLine(x, y + h - 1, w, color);
    drawFastVLine(x, y, h, color);
    drawFastVLine(x + w - 1, y, h, color);
  }

  void fillRect(int x, int y, int w, int h, uint16_t color) {
    setWindow(x, y, w, h);
    writeCommand(0x2C);
    digitalWrite(TFT_DC, HIGH);
    digitalWrite(TFT_CS, LOW);
    
    uint8_t hi = color >> 8;
    uint8_t lo = color & 0xFF;
    for (int i = 0; i < w * h; i++) {
      SPI.transfer(hi);
      SPI.transfer(lo);
    }
    digitalWrite(TFT_CS, HIGH);
  }
  
 
  void drawPixel(int x, int y, uint16_t color) {
    int tx = x, ty = y;
    switch (rotation) {
      case 1:
        tx = y;
        ty = _height - x - 1;
        break;
      case 2:
        tx = _width - x - 1;
        ty = _height - y - 1;
        break;
      case 3:
        tx = _width - y - 1;
        ty = x;
        break;
    }

    if (tx < 0 || tx >= _width || ty < 0 || ty >= _height) return;

    writeCommand(0x2A);
    writeData(0x00); writeData(tx + COL_OFFSET);
    writeData(0x00); writeData(tx + COL_OFFSET);
    
    writeCommand(0x2B);
    writeData(0x00); writeData(ty + ROW_OFFSET);
    writeData(0x00); writeData(ty + ROW_OFFSET);
    
    writeCommand(0x2C);
    digitalWrite(TFT_DC, HIGH);
    digitalWrite(TFT_CS, LOW);
    SPI.transfer(color >> 8);
    SPI.transfer(color & 0xFF);
    digitalWrite(TFT_CS, HIGH);
  }

  // 这个函数给恐龙用 → 自动180°翻转，解决上下左右颠倒
void drawImage(int x, int y, int w, int h, const uint16_t* img) {
  if (!img) return;
  setWindow(x, y, w, h);
  
  writeCommand(0x2C);
  digitalWrite(TFT_DC, HIGH);
  digitalWrite(TFT_CS, LOW);
    for (int j = h-1; j >= 0; j--) {        // 行反转
      for (int i = w-1; i >= 0; i--) {      // 列反转
        uint16_t color = pgm_read_word(&img[j * w + i]);
        SPI.transfer(color >> 8);
        SPI.transfer(color & 0xFF);
      }
    }
  
  
  digitalWrite(TFT_CS, HIGH);
}
  
  void drawChar(char c, int x, int y, uint16_t color) {
    int index = c - 32;
    if (index < 0 || index > 94) return;
    
    for (int row = 0; row < 8; row++) {
      uint8_t line = pgm_read_byte(&font8x8[index][row]);
      for (int col = 0; col < 8; col++) {
        if (line & (0x80 >> col)) {
          drawPixel(x + col, y + row, color);
        }
      }
    }
  }
void drawSmallChar(char c, int x, int y, uint16_t color) {
  int index = -1;
  
  // 数字 0-9
  if (c >= '0' && c <= '9') {
    index = c - '0';
  }
  // 运算符
  else {
    switch(c) {
      case '+': index = 10; break;
      case '-': index = 11; break;
      case '*': index = 12; break;
      case '/': index = 13; break;
      case '=': index = 14; break;
      case '%': index = 15; break;
      case '(': index = 16; break;
      case ')': index = 17; break;
      case '.': index = 18; break;
      case '^': index = 19; break;
      case 'V': index = 20; break;  // 根号用V表示
      case '<': index = 21; break;  // 左箭头
      case ' ': index = 22; break;  // 空格
      case 'R': index = 23; break;  // RET用R表示
      default: return;
    }
  }
  
  if (index < 0 || index > 23) return;
  
  if (x + 4 > SCREEN_WIDTH || y + 7 > SCREEN_HEIGHT) return;
  if (x < 0 || y < 0) return;
  
  for (int row = 0; row < 7; row++) {
    uint8_t line = pgm_read_byte(&font4x7[index][row]);
    for (int col = 0; col < 4; col++) {
      if (line & (0x08 >> col)) {
        drawPixel(x + col, y + row, color);
      }
    }
  }
}
// 绘制字符串
void drawSmallString(const char* str, int x, int y, uint16_t color) {
  int offset = 0;
  while (*str) {
    drawSmallChar(*str, x + offset, y, color);
    offset += 5; 
    str++;
  }
}
  // 镜像图片（专门给主界面背景用）
void drawImageMirror(int x, int y, int w, int h, const uint16_t* img) {
  if (!img) return;
  setWindow(x, y, w, h);
  
  writeCommand(0x2C);
  digitalWrite(TFT_DC, HIGH);
  digitalWrite(TFT_CS, LOW);

  // 水平镜像（只给背景用）
  for (int j = 0; j < h; j++) {
    for (int i = w-1; i >= 0; i--) {
      uint16_t color = pgm_read_word(&img[j * w + i]);
      SPI.transfer(color >> 8);
      SPI.transfer(color & 0xFF);
    }
  }
  
  digitalWrite(TFT_CS, HIGH);
}

// 显示30x30图片
void showImage30x30Fast(const uint8_t* img, int x, int y) {
  if (!img) return;
  
  // Image2LCD格式：前8字节是头信息
  int idx = 8;
  const int width = 30;
  const int height = 30;
  
  for (int row = 0; row < height; row++) {
    for (int col = 0; col < width; col++) {
      uint8_t high = img[idx++];
      uint8_t low = img[idx++];
      uint16_t color = (high << 8) | low;
      drawPixel(x + col, y + row, color); 
    }
  }
}
  void drawLargeDigit(char c, int x, int y, uint16_t color) {
    if (c < '0' || c > '9') return;
    int index = c - '0';
    
    if (x < 0 || x + 16 > _width || y < 0 || y + 24 > _height) return;
    
    for (int row = 0; row < 24; row++) {
      uint16_t line = (pgm_read_byte(&font16x24[index][row*2]) << 8) | 
                        pgm_read_byte(&font16x24[index][row*2+1]);
      for (int col = 0; col < 16; col++) {
        if (line & (0x8000 >> col)) {
          drawPixel(x + col, y + row, color);
        }
      }
    }
  }
  
